n = int(input("Donner un entier entre 0 et 6 : "))

if n == 0:
    print("Dimanche")
elif n == 1:
    print("Lundi")
elif n == 2:
    print("Mardi")
elif n == 3:
    print("Mercredi")
elif n == 4:
    print("Jeudi")
elif n == 5:
    print("Vendredi")
elif n == 6:
    print("Samedi")
else:
    print("Erreur : valeur invalide")